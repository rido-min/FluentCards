namespace FluentCards;

/// <summary>
/// Specifies the style of a container.
/// </summary>
public enum ContainerStyle
{
    /// <summary>
    /// Default container style.
    /// </summary>
    Default,

    /// <summary>
    /// Emphasis container style.
    /// </summary>
    Emphasis,

    /// <summary>
    /// Good container style (typically green).
    /// </summary>
    Good,

    /// <summary>
    /// Attention container style (typically red).
    /// </summary>
    Attention,

    /// <summary>
    /// Warning container style (typically yellow/orange).
    /// </summary>
    Warning,

    /// <summary>
    /// Accent container style.
    /// </summary>
    Accent
}
