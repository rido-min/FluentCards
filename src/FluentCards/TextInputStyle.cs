namespace FluentCards;

/// <summary>
/// Specifies the style for text input.
/// </summary>
public enum TextInputStyle
{
    /// <summary>
    /// Normal text input.
    /// </summary>
    Text,

    /// <summary>
    /// Telephone number input.
    /// </summary>
    Tel,

    /// <summary>
    /// URL input.
    /// </summary>
    Url,

    /// <summary>
    /// Email address input.
    /// </summary>
    Email,

    /// <summary>
    /// Password input (hidden text).
    /// </summary>
    Password
}
